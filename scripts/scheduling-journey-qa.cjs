const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const base = process.env.BASE_URL || 'http://127.0.0.1:4174'
;(async () => {
  const browser = await chromium.launch({ headless: true, ...(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {}) })
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  const errors = [], checks = []
  page.on('pageerror', error => errors.push(error.message))
  page.setDefaultTimeout(6000)
  fs.mkdirSync('qa/scheduling-journey', { recursive: true })
  try {
    await page.goto(base + '/projects/scheduling/')
    const map = page.getByTestId('scheduling-journey-map')
    await map.waitFor()
    assert.equal(await map.locator('button[data-stage]').count(), 6)
    for (const id of ['question', 'model', 'dispatch', 'validation', 'comparison', 'reproduce']) assert.equal(await page.locator(`nav[aria-label="Build journey"] a[href="#${id}"]`).count(), 1)
    await map.locator('[data-stage="dispatch"]').click()
    assert.match(await map.getByTestId('scheduling-map-artifact').innerText(), /FCFS|SPT/)
    await map.locator('[data-stage="reproduce"]').focus()
    await page.keyboard.press('Enter')
    assert.equal(await map.getByRole('link', { name: 'Explore this stage' }).getAttribute('href'), '#reproduce')
    checks.push('Six development stages have clickable artifacts and keyboard chapter links')

    const dispatch = page.getByTestId('scheduling-dispatch')
    const fact = name => dispatch.locator(`[data-job-${name}]`).innerText()
    await dispatch.getByRole('button', { name: 'FCFS', exact: true }).click()
    await dispatch.getByRole('button', { name: 'Inspect long job', exact: true }).click()
    assert.equal(await fact('id'), 'long-job')
    assert.equal(await fact('start'), '0')
    assert.equal(await fact('wait'), '0')
    await dispatch.getByRole('button', { name: 'SPT', exact: true }).click()
    assert.equal(await fact('id'), 'short-00')
    assert.equal(await dispatch.locator('[data-ready-count]').innerText(), '2')
    assert.equal(await dispatch.locator('[data-future-count]').innerText(), '30')
    await dispatch.getByRole('button', { name: 'Inspect long job', exact: true }).click()
    assert.equal(await fact('start'), '93')
    assert.equal(await fact('end'), '118')
    assert.equal(await fact('wait'), '93')
    checks.push('Saved FCFS/SPT paths expose the long-job trade-off without using future arrivals')
    await dispatch.getByLabel('Recorded scenario', { exact: true }).selectOption('sparse-arrivals')
    await dispatch.getByRole('button', { name: 'Next dispatch', exact: true }).click()
    assert.equal(await fact('start'), '40')
    assert.equal(await fact('wait'), '0')
    await dispatch.getByLabel('Inspect job', { exact: true }).selectOption('J011')
    assert.equal(await fact('start'), '440')
    assert.equal(await fact('end'), '450')
    checks.push('Sparse replay preserves idle gaps, zero waits and the recorded final finish')
    await dispatch.getByRole('button', { name: 'Replay schedule', exact: true }).click()
    assert.equal(await dispatch.getAttribute('data-playing'), 'true')
    await dispatch.getByRole('button', { name: 'Pause schedule', exact: true }).click()
    assert.equal(await dispatch.getAttribute('data-playing'), 'false')
    await dispatch.getByRole('button', { name: 'Replay schedule', exact: true }).click()
    await dispatch.getByLabel('Recorded scenario', { exact: true }).selectOption('steady-short-arrivals')
    await dispatch.getByRole('button', { name: 'FCFS', exact: true }).click()
    await page.waitForTimeout(800)
    assert.equal(await dispatch.getAttribute('data-playing'), 'false')
    assert.equal(await fact('id'), 'long-job')
    checks.push('Playback pauses and changing policy/scenario cancels the previous replay')

    const validation = page.getByTestId('scheduling-validation')
    for (const [sample, outcome, gate] of [['valid', 'Accepted', 'Available'], ['gap', 'Rejected', 'Blocked'], ['release', 'Rejected', 'Blocked'], ['duplicate', 'Rejected', 'Blocked']]) {
      await validation.locator(`[data-validation-case="${sample}"]`).click()
      await validation.locator('button[data-check]').last().click()
      assert.equal(await validation.locator('[data-validation-outcome]').innerText(), outcome)
      assert.equal(await validation.locator('[data-metrics-gate]').innerText(), gate)
    }
    await validation.locator('[data-validation-case="gap"]').click()
    await validation.getByRole('button', { name: 'Replay checks', exact: true }).click()
    await page.waitForFunction(() => document.querySelector('[data-testid="scheduling-validation"]').dataset.playing === 'false', null, { timeout: 8000 })
    assert.equal(await validation.locator('[data-metrics-gate]').innerText(), 'Blocked')
    assert.match(await validation.innerText(), /overlap_or_missing_gap/)
    checks.push('Invalid release, coverage and changeover candidates cannot enter metric calculation')

    const comparison = page.getByTestId('scheduling-comparison')
    const metricValue = policy => comparison.locator(`[data-metric-policy="${policy}"]`).innerText()
    assert.equal(await metricValue('fcfs'), '26.16')
    assert.equal(await metricValue('spt'), '2.91')
    await comparison.getByRole('button', { name: 'Longest wait', exact: true }).focus()
    await page.keyboard.press('Enter')
    assert.equal(await metricValue('fcfs'), '27.00')
    assert.equal(await metricValue('spt'), '93.00')
    await comparison.getByLabel('Compare recorded scenario', { exact: true }).selectOption('sparse-arrivals')
    assert.equal(await metricValue('fcfs'), '0.00')
    assert.equal(await metricValue('spt'), '0.00')
    assert.equal(await comparison.getByLabel('Compare recorded scenario', { exact: true }).locator('option').count(), 22)
    checks.push('All 22 scenarios are selectable; mean/max comparison preserves exact recorded values')

    await dispatch.getByRole('button', { name: 'Replay schedule', exact: true }).click()
    await validation.getByRole('button', { name: 'Replay checks', exact: true }).click()
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.waitForFunction(() => ['scheduling-dispatch', 'scheduling-validation'].every(id => document.querySelector(`[data-testid="${id}"]`).dataset.playing === 'false'))
    await dispatch.getByRole('button', { name: 'Inspect long job', exact: true }).focus()
    await page.keyboard.press('Enter')
    assert.equal(await fact('id'), 'long-job')
    await validation.locator('[data-validation-case="valid"]').click()
    await validation.locator('button[data-check]').last().focus()
    await page.keyboard.press('Enter')
    assert.equal(await validation.locator('[data-metrics-gate]').innerText(), 'Available')
    await map.locator('[data-stage="comparison"]').click()
    await comparison.getByRole('button', { name: 'Average wait', exact: true }).click()
    assert.equal(await page.evaluate(() => document.getAnimations().filter(a => a.playState === 'running').length), 0)
    checks.push('Live reduced-motion changes stop timers and preserve keyboard/manual exploration')

    for (const width of [320, 390, 768, 1440]) {
      await page.setViewportSize({ width, height: 1000 })
      for (const [name, locator] of [['map', map], ['dispatch', dispatch], ['validation', validation], ['comparison', comparison]]) {
        await locator.scrollIntoViewIfNeeded()
        assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${name}: overflow at ${width}`)
        await locator.screenshot({ path: `qa/scheduling-journey/${name}-${width}.png` })
      }
    }
    checks.push('All diagrams fit 320, 390, 768 and 1440px screens')
    const chunk = fs.readdirSync('dist/assets').find(name => /^SchedulingCase-.*\.js$/.test(name))
    assert(chunk)
    for (const id of ['scheduling-build-map', 'dispatch']) {
      const cold = await browser.newPage({ viewport: { width: 390, height: 844 } })
      await cold.route(`${base}/assets/${chunk}`, async route => {
        const response = await route.fetch()
        await new Promise(resolve => setTimeout(resolve, 750))
        await route.fulfill({ response })
      })
      await cold.goto(`${base}/projects/scheduling/#${id}`)
      await cold.getByTestId('scheduling-journey-map').waitFor()
      await cold.waitForFunction(id => {
        const top = document.getElementById(id)?.getBoundingClientRect().top
        return top !== undefined && scrollY > 0 && top >= 0 && top < innerHeight / 2
      }, id)
      await cold.close()
    }
    checks.push('Cold chapter links reach the requested diagram after delayed case loading')
    await page.setViewportSize({ width: 1440, height: 1200 })
    await page.locator('nav[aria-label="Build journey"] a[href="#reproduce"]').click()
    await page.waitForFunction(() => document.querySelector('nav[aria-label="Build journey"] a[href="#reproduce"]')?.getAttribute('aria-current') === 'step')
    for (const path of ['/evidence/scheduling-inputs.json', '/evidence/scheduling-timelines.json', '/evidence/scheduling-results.json', '/evidence/scheduling-results.csv', '/evidence/scheduling-development.md', '/evidence/scheduling-readme.md', '/downloads/scheduling-simulation-study.zip']) assert.equal((await page.request.get(base + path)).status(), 200, path)
    assert.deepEqual(errors, [])
    checks.push('Final chapter, saved evidence and source bundle remain usable without page errors')
    fs.writeFileSync('qa/scheduling-journey/results.json', JSON.stringify({ checkedAt: new Date().toISOString(), checks }, null, 2) + '\n')
    console.log(`${checks.length} scheduling journey checks passed`)
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
