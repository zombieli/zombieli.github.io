const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const base = process.env.BASE_URL || 'http://127.0.0.1:4174'
const corpus = JSON.parse(fs.readFileSync('src/data/manual-corpus.json', 'utf8'))
const saved = JSON.parse(fs.readFileSync('src/data/manual-evaluation.json', 'utf8'))
;(async () => {
  const browser = await chromium.launch({ headless: true, ...(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {}) })
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  const errors = [], checks = [], external = [], dialogs = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => { if (!request.url().startsWith(base)) external.push(request.url()) })
  page.on('dialog', async dialog => { dialogs.push(dialog.message()); await dialog.dismiss() })
  page.setDefaultTimeout(6000)
  fs.mkdirSync('qa/manual-journey', { recursive: true })
  try {
    await page.goto(base + '/projects/technical-manual-search/')
    const map = page.getByTestId('manual-journey-map')
    await map.waitFor()
    assert.equal(await map.locator('button[data-stage]').count(), 6)
    for (const id of ['question', 'corpus', 'ranking', 'sources', 'evaluation', 'reproduce']) {
      await map.locator(`[data-stage="${id}"]`).click()
      assert.equal(await map.getByRole('link', { name: 'Explore this stage' }).getAttribute('href'), '#' + id)
      assert.equal(await page.locator(`nav[aria-label="Build journey"] a[href="#${id}"]`).count(), 1)
    }
    await map.locator('[data-stage="ranking"]').focus()
    await page.keyboard.press('Enter')
    assert.match(await map.getByTestId('manual-map-artifact').innerText(), /BM25/)
    checks.push('Six clickable source-grounded stages and keyboard chapter links are available')

    const ranking = page.getByTestId('manual-ranking')
    const query = ranking.getByLabel('Query', { exact: true })
    const submit = () => ranking.getByRole('button', { name: 'Run search', exact: true }).click()
    assert.equal(await ranking.locator('[data-result-ref]').count(), 1)
    assert.equal(await ranking.locator('[data-result-ref]').first().getAttribute('data-result-ref'), 'aurora-beacon#battery-replacement')
    const exactScore = await ranking.locator('[data-result-ref]').first().getAttribute('data-score')
    await ranking.getByRole('button', { name: 'Repeated / full-width', exact: true }).click()
    assert.equal(await ranking.locator('[data-result-ref]').first().getAttribute('data-score'), exactScore)
    assert.equal(await ranking.getByTestId('manual-tokens').innerText(), 'battery\nreplacement')
    await ranking.getByRole('button', { name: 'Paraphrase miss', exact: true }).click()
    assert.equal(await ranking.locator('[data-result-ref]').first().getAttribute('data-result-ref'), 'cedar-logger#missing-samples')
    await ranking.getByRole('button', { name: 'Unsupported question', exact: true }).click()
    assert.match(await ranking.getByTestId('manual-ranked-source').innerText(), /cedar-logger#csv-export/)
    assert.match(await ranking.locator('[data-result-ref]').first().innerText(), /2\/3 terms/)
    checks.push('Original ranking preserves normalisation, deduplication, paraphrase miss and partial unsupported overlap')

    await query.fill('cable')
    await query.press('Enter')
    const globalScores = await ranking.locator('[data-result-ref]').evaluateAll(elements => Object.fromEntries(elements.map(element => [element.dataset.resultRef, element.dataset.score])))
    await ranking.getByLabel('Manual filter', { exact: true }).selectOption('mariner-cart')
    await submit()
    for (const item of await ranking.locator('[data-result-ref]').all()) assert.equal(await item.getAttribute('data-score'), globalScores[await item.getAttribute('data-result-ref')])
    await ranking.locator('[data-ranking-step="1"]').click()
    assert.equal(await ranking.getByTestId('manual-eligible').innerText(), '5')
    await ranking.getByLabel('Category filter', { exact: true }).selectOption('Data handling')
    await submit()
    assert.equal(await ranking.locator('[data-result-ref]').count(), 0)
    await ranking.getByTestId('manual-no-results').waitFor()
    await ranking.getByRole('button', { name: 'Exact task', exact: true }).click()
    assert.equal(await ranking.getByLabel('Manual filter', { exact: true }).inputValue(), '')
    assert.equal(await ranking.getByLabel('Category filter', { exact: true }).inputValue(), '')
    await query.fill('x'.repeat(241)); await submit()
    assert.match(await ranking.getByTestId('manual-search-error').innerText(), /240/)
    assert.equal(await ranking.locator('[data-result-ref]').count(), 0)
    for (const value of ['the and of', 'satellite ephemeris']) { await query.fill(value); await submit(); await ranking.getByTestId('manual-no-results').waitFor() }
    await ranking.getByRole('button', { name: 'Exact task', exact: true }).click()
    await ranking.getByText('Read the exact source paragraph', { exact: true }).click()
    assert.equal(await ranking.getByTestId('manual-ranking-full-source').innerText(), corpus[0].sections[1].text)
    checks.push('Intersecting filters retain global scores; invalid input clears results and full source remains exact')

    const source = page.getByTestId('manual-attribution')
    await source.getByRole('button', { name: 'Literal markup', exact: true }).click()
    assert.equal(await source.getByTestId('manual-exact-source').innerText(), corpus[1].sections[4].text)
    assert.equal(await source.locator('img').count(), 0)
    await source.locator('[data-source-step="1"]').focus()
    await page.keyboard.press('Enter')
    assert.equal(await source.locator('[data-source-step="1"]').getAttribute('aria-pressed'), 'true')
    assert(await source.locator('[data-source-step="1"]').evaluate(element => element === document.activeElement))
    const literalLink = await source.getByTestId('manual-source-link').getAttribute('href')
    assert.equal(new URL(literalLink, base).hash, '#source-cedar-logger.label-literals')
    await source.getByRole('button', { name: 'Unsupported encryption', exact: true }).click()
    assert.match(await source.getByTestId('manual-source-note').innerText(), /no encryption information/)
    assert.equal(await source.getByTestId('manual-exact-source').innerText(), corpus[1].sections[2].text)
    checks.push('Source trace preserves literal markup, exact paragraphs and the unsupported-query distinction')

    const demo = await browser.newPage({ viewport: { width: 390, height: 844 } })
    const demoErrors = []
    demo.on('pageerror', error => demoErrors.push(error.message))
    demo.on('dialog', async dialog => { dialogs.push(dialog.message()); await dialog.dismiss() })
    await demo.goto(base + literalLink)
    await demo.locator('#source-cedar-logger\\.label-literals details[open]').waitFor()
    assert.equal(await demo.locator('#source-cedar-logger\\.label-literals .source-text').innerText(), corpus[1].sections[4].text)
    assert.equal(await demo.locator('#manual-filter').inputValue(), 'cedar-logger')
    await demo.reload()
    await demo.locator('#source-cedar-logger\\.label-literals details[open]').waitFor()
    assert.deepEqual(demoErrors, [])
    await demo.close()
    checks.push('Actual source links open the correct original-demo disclosure and retain filters after reload')

    const evaluation = page.getByTestId('manual-evaluation')
    assert.equal(await evaluation.locator('button[data-query-id]').count(), 26)
    for (const row of saved.rows) {
      await evaluation.locator(`[data-query-id="${row.id}"]`).click()
      assert.equal(await evaluation.getByTestId('manual-eval-query').innerText(), row.query)
      const outcome = row.kind === 'positive' ? row.hitAtK ? 'Relevant section found' : 'Relevant section missed' : row.falsePositive ? 'Lexical false positive' : 'No result · expected'
      assert.equal(await evaluation.getByTestId('manual-eval-outcome').innerText(), outcome)
      const returned = await evaluation.getByTestId('manual-eval-returned').innerText()
      for (const reference of row.returned.slice(0, 5)) assert(returned.includes(reference), row.id)
    }
    await evaluation.locator('[data-query-id="p17"]').click()
    assert.match(await evaluation.getByTestId('manual-eval-metrics').innerText(), /Not found/)
    assert.match(await evaluation.getByTestId('manual-eval-returned').innerText(), /missing-samples/)
    await evaluation.locator('[data-query-id="n06"]').click()
    assert.match(await evaluation.getByTestId('manual-eval-metrics').innerText(), /8 queries/)
    assert.match(await evaluation.getByTestId('manual-eval-outcome').innerText(), /Lexical false positive/)
    checks.push('All 26 recorded outcomes retain correct labels, top-five results and separate metric denominators')

    await ranking.getByRole('button', { name: 'Replay retrieval', exact: true }).click()
    await ranking.getByRole('button', { name: 'Pause retrieval', exact: true }).click()
    const stopped = await ranking.locator('[data-ranking-step][aria-pressed="true"]').getAttribute('data-ranking-step')
    await page.waitForTimeout(1300)
    assert.equal(await ranking.locator('[data-ranking-step][aria-pressed="true"]').getAttribute('data-ranking-step'), stopped)
    await ranking.getByRole('button', { name: 'Replay retrieval', exact: true }).click()
    await ranking.getByRole('button', { name: 'Exact task', exact: true }).click()
    assert.equal(await ranking.getAttribute('data-playing'), 'false')
    await evaluation.getByRole('button', { name: 'Replay query set', exact: true }).click()
    await evaluation.getByRole('button', { name: 'Pause evaluation', exact: true }).click()
    const pausedQuery = await evaluation.getByTestId('manual-eval-query').innerText()
    await page.waitForTimeout(1300)
    assert.equal(await evaluation.getByTestId('manual-eval-query').innerText(), pausedQuery)
    await evaluation.getByRole('button', { name: 'Replay query set', exact: true }).click()
    await evaluation.locator('[data-query-id="p17"]').click()
    assert.equal(await evaluation.getAttribute('data-playing'), 'false')
    checks.push('Replay pauses; new queries and manual selections cancel pending animation')

    await ranking.getByRole('button', { name: 'Replay retrieval', exact: true }).click()
    await evaluation.getByRole('button', { name: 'Replay query set', exact: true }).click()
    await map.locator('[data-stage="evaluation"]').click()
    await source.locator('[data-source-step="0"]').click()
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.waitForFunction(() => ['manual-ranking', 'manual-evaluation', 'manual-journey-map'].every(id => document.querySelector(`[data-testid="${id}"]`).dataset.playing === 'false'))
    await evaluation.locator('[data-query-id="p17"]').focus(); await page.keyboard.press('Enter')
    await ranking.locator('[data-ranking-step="2"]').focus(); await page.keyboard.press('Enter')
    assert.equal(await evaluation.getByTestId('manual-eval-outcome').innerText(), 'Relevant section missed')
    assert.equal(await page.evaluate(() => document.getAnimations().filter(animation => animation.playState === 'running').length), 0)
    checks.push('Runtime reduced motion stops all replay and CSS motion while keyboard exploration remains available')

    for (const width of [320, 390, 768, 1440]) {
      await page.setViewportSize({ width, height: 1000 })
      for (const [name, locator] of [['map', map], ['ranking', ranking], ['source', source], ['evaluation', evaluation]]) {
        await locator.scrollIntoViewIfNeeded()
        assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${name}: overflow at ${width}`)
        await locator.screenshot({ path: `qa/manual-journey/${name}-${width}.png` })
      }
    }
    checks.push('All four diagrams fit 320, 390, 768 and 1440px screens')
    const chunk = fs.readdirSync('dist/assets').find(name => /^ManualCase-.*\.js$/.test(name))
    assert(chunk)
    for (const id of ['manual-build-map', 'ranking', 'sources', 'evaluation']) {
      const cold = await browser.newPage({ viewport: { width: 390, height: 844 } })
      await cold.route(`${base}/assets/${chunk}`, async route => { const response = await route.fetch(); await new Promise(resolve => setTimeout(resolve, 750)); await route.fulfill({ response }) })
      await cold.goto(`${base}/projects/technical-manual-search/#${id}`)
      await cold.getByTestId('manual-journey-map').waitFor()
      await cold.waitForFunction(id => { const top = document.getElementById(id)?.getBoundingClientRect().top; return top !== undefined && scrollY > 0 && top >= 0 && top < innerHeight / 2 }, id)
      await cold.close()
    }
    checks.push('Cold chapter navigation restores the requested section after delayed component loading')
    for (const path of ['/demos/technical-manual-search/', '/evidence/technical-manual-search-readme.md', '/evidence/technical-manual-search-architecture.md', '/evidence/technical-manual-search-queries.json', '/evidence/technical-manual-search-evaluation.json', '/evidence/technical-manual-search-verification.json', '/evidence/technical-manual-search-development.md', '/downloads/technical-manual-search.zip']) assert.equal((await page.request.get(base + path)).status(), 200, path)
    assert.deepEqual(errors, []); assert.deepEqual(external, []); assert.deepEqual(dialogs, [])
    assert.equal((await page.evaluate(() => indexedDB.databases())).length, 0)
    checks.push('Evidence and demo links remain available without page errors, external requests, dialogs or storage writes')
    // Viewport capture avoids off-screen fixed elements appearing in tall locator captures.
    await page.setViewportSize({ width: 390, height: 844 })
    await page.evaluate(() => document.activeElement?.blur())
    await ranking.evaluate(element => element.scrollIntoView({ block: 'start', behavior: 'instant' }))
    const skip = await page.locator('.skip').boundingBox()
    assert(skip && skip.y + skip.height <= 0)
    await page.screenshot({ path: 'qa/manual-journey/ranking-mobile-viewport.png' })
    fs.writeFileSync('qa/manual-journey/results.json', JSON.stringify({ checkedAt: new Date().toISOString(), checks }, null, 2) + '\n')
    console.log(`${checks.length} manual journey checks passed`)
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
