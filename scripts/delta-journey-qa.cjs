const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const base = process.env.BASE_URL || 'http://127.0.0.1:4174'
;(async () => {
  const browser = await chromium.launch({ headless: true, ...(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {}) })
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  const errors = [], checks = [], external = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => { if (!request.url().startsWith(base)) external.push(request.url()) })
  page.setDefaultTimeout(6000)
  fs.mkdirSync('qa/delta-journey', { recursive: true })
  try {
    await page.goto(base + '/projects/test-report-delta/')
    const map = page.getByTestId('delta-journey-map')
    await map.waitFor()
    assert.equal(await map.locator('button[data-stage]').count(), 6)
    for (const id of ['question', 'contract', 'comparison', 'policy', 'verification', 'reproduce']) {
      await map.locator(`[data-stage="${id}"]`).click()
      assert.equal(await map.getByRole('link', { name: 'Explore this stage' }).getAttribute('href'), '#' + id)
      assert.equal(await page.locator(`nav[aria-label="Build journey"] a[href="#${id}"]`).count(), 1)
    }
    await map.locator('[data-stage="comparison"]').focus()
    await page.keyboard.press('Enter')
    assert.match(await map.getByTestId('delta-map-artifact').innerText(), /pure core/)
    checks.push('Six clickable development stages expose their actual artifacts and keyboard chapter links')

    const compare = page.getByTestId('delta-comparison')
    assert.equal(await compare.locator('button[data-case]').count(), 8)
    const expected = [['failed', 'failed', 'persistent failure', 'unavailable'], ['passed', 'failed', 'regression', 'unavailable'], ['failed', 'passed', 'recovery', 'unavailable'], ['passed', 'passed', 'unchanged', 'slower'], ['passed', 'passed', 'unchanged', 'stable'], ['passed', 'absent', 'removed', 'unavailable'], ['absent', 'passed', 'added', 'unavailable'], ['passed', 'skipped', 'new skipped', 'unavailable']]
    for (const [index, [before, after, kind, timing]] of expected.entries()) {
      await compare.locator(`[data-case="${index}"]`).click()
      assert.equal(await compare.getByTestId('delta-before').innerText(), before)
      assert.equal(await compare.getByTestId('delta-after').innerText(), after)
      assert.equal(await compare.getByTestId('delta-kind').innerText(), kind)
      assert.equal(await compare.getByTestId('delta-timing').innerText(), timing)
    }
    checks.push('All eight original sample identities retain exact transitions, missing sides and timing facets')
    await compare.getByRole('button', { name: 'Replay matching', exact: true }).click()
    assert.equal(await compare.getAttribute('data-playing'), 'true')
    await compare.getByRole('button', { name: 'Pause matching', exact: true }).click()
    const paused = await compare.getByTestId('delta-kind').innerText()
    await page.waitForTimeout(1300)
    assert.equal(await compare.getByTestId('delta-kind').innerText(), paused)
    await compare.getByRole('button', { name: 'Replay matching', exact: true }).click()
    await compare.locator('[data-case="5"]').click()
    await page.waitForTimeout(1300)
    assert.equal(await compare.getAttribute('data-playing'), 'false')
    assert.equal(await compare.getByTestId('delta-kind').innerText(), 'removed')
    checks.push('Matching replay pauses and manual selection cancels pending playback')

    const policy = page.getByTestId('delta-policy')
    const verdict = () => policy.getByTestId('delta-verdict').innerText()
    assert.equal(await verdict(), 'fail')
    assert.match(await policy.getByTestId('delta-reasons').innerText(), /2 candidate test\(s\) failed/)
    await policy.getByLabel('Allow removed tests', { exact: true }).check()
    await policy.getByLabel('Allow newly skipped tests', { exact: true }).check()
    assert.equal(await verdict(), 'fail')
    await policy.locator('[data-policy-scenario="coverage"]').click()
    assert.equal(await verdict(), 'incomplete')
    await policy.getByLabel('Allow removed tests', { exact: true }).check()
    assert.equal(await verdict(), 'incomplete')
    await policy.getByLabel('Allow newly skipped tests', { exact: true }).check()
    assert.equal(await verdict(), 'pass')
    assert.equal(await policy.getByTestId('delta-exit').innerText(), '0')
    for (const [scenario, expected] of [['empty', 'incomplete'], ['added-failure', 'fail']]) {
      await policy.locator(`[data-policy-scenario="${scenario}"]`).click()
      await policy.getByLabel('Allow removed tests', { exact: true }).check()
      await policy.getByLabel('Allow newly skipped tests', { exact: true }).check()
      assert.equal(await verdict(), expected)
      assert.equal(await policy.getByTestId('delta-exit').innerText(), '1')
    }
    await policy.locator('[data-gate="0"]').focus()
    await page.keyboard.press('Enter')
    assert.equal(await policy.locator('[data-gate="0"]').getAttribute('aria-pressed'), 'true')
    assert(await policy.locator('[data-gate="0"]').evaluate(element => element === document.activeElement))
    checks.push('Coverage exceptions are independent, failures and empty candidates cannot pass, and gate focus is retained')

    await policy.locator('[data-policy-scenario="timing"]').click()
    assert.equal(await verdict(), 'pass')
    await policy.getByRole('button', { name: 'At both limits', exact: true }).click()
    assert.match(await policy.getByTestId('delta-policy-timing').innerText(), /stable/)
    await policy.getByRole('button', { name: 'Just over both', exact: true }).click()
    assert.match(await policy.getByTestId('delta-policy-timing').innerText(), /slower/)
    assert.equal(await verdict(), 'pass')
    await policy.getByRole('button', { name: 'Zero baseline', exact: true }).click()
    assert.match(await policy.getByTestId('delta-policy-timing').innerText(), /undefined \(JSON null\)/)
    await policy.getByLabel('Baseline time (ms)', { exact: true }).fill('450')
    await policy.getByLabel('Candidate time (ms)', { exact: true }).fill('100')
    assert.match(await policy.getByTestId('delta-policy-timing').innerText(), /faster/)
    await policy.getByLabel('Ratio limit', { exact: true }).fill('1')
    assert.equal(await verdict(), 'No verdict')
    assert.match(await policy.getByTestId('delta-policy-error').innerText(), /Invalid policy/)
    await policy.getByLabel('Ratio limit', { exact: true }).fill('')
    assert.match(await policy.getByTestId('delta-policy-error').innerText(), /Enter all timing/)
    await policy.getByLabel('Ratio limit', { exact: true }).fill('1.5')
    assert.equal(await verdict(), 'pass')
    checks.push('Strict timing boundaries, zero ratios, speedups and invalid thresholds behave like the original core')

    const race = page.getByTestId('delta-race')
    assert.equal(await race.getByTestId('delta-race-verdict').innerText(), 'pass')
    await race.locator('[data-race-step="1"]').click()
    assert.equal(await race.getByTestId('delta-race-verdict').innerText(), 'No verdict')
    assert.equal(await race.getByTestId('delta-race-download').innerText(), 'Download unavailable')
    await race.locator('[data-race-step="4"]').click()
    assert.match(await race.getByTestId('delta-race-event').innerText(), /ignored/)
    assert.match(await race.locator('[data-slot="candidate"]').innerText(), /Malformed JSON/)
    assert.equal(await race.getByTestId('delta-race-verdict').innerText(), 'No verdict')
    await race.getByRole('button', { name: 'Independent sample reads', exact: true }).click()
    await race.locator('[data-race-step="3"]').click()
    assert.match(await race.locator('[data-slot="baseline"]').innerText(), /Reading/)
    assert.equal(await race.getByTestId('delta-race-verdict').innerText(), 'No verdict')
    await race.locator('[data-race-step="5"]').click()
    assert.match(await race.locator('[data-slot="baseline"]').innerText(), /Sample baseline/)
    assert.match(await race.locator('[data-slot="candidate"]').innerText(), /New candidate/)
    assert.equal(await race.getByTestId('delta-race-verdict').innerText(), 'pass')
    checks.push('Late old reads cannot restore stale acceptance; independent baseline completion preserves the newer candidate')
    await race.getByRole('button', { name: 'Replay reads', exact: true }).click()
    await race.getByRole('button', { name: 'Pause reads', exact: true }).click()
    const event = await race.getByTestId('delta-race-event').innerText()
    await page.waitForTimeout(1300)
    assert.equal(await race.getByTestId('delta-race-event').innerText(), event)
    await race.getByRole('button', { name: 'Replay reads', exact: true }).click()
    await race.getByRole('button', { name: 'Old read finishes late', exact: true }).click()
    await page.waitForTimeout(1300)
    assert.match(await race.getByTestId('delta-race-event').innerText(), /accepted comparison/)
    assert.equal(await race.getAttribute('data-playing'), 'false')
    checks.push('Read replay pauses and changing race scenario clears the previous timer')

    await compare.getByRole('button', { name: 'Replay matching', exact: true }).click()
    await race.getByRole('button', { name: 'Replay reads', exact: true }).click()
    await map.locator('[data-stage="policy"]').click()
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.waitForFunction(() => ['delta-comparison', 'delta-race', 'delta-journey-map'].every(id => document.querySelector(`[data-testid="${id}"]`).dataset.playing === 'false'))
    await compare.locator('[data-case="3"]').focus()
    await page.keyboard.press('Enter')
    assert.equal(await compare.getByTestId('delta-timing').innerText(), 'slower')
    await policy.getByRole('button', { name: 'Just over both', exact: true }).click()
    await race.locator('[data-race-step="4"]').focus()
    await page.keyboard.press('Enter')
    assert.equal(await race.getByTestId('delta-race-verdict').innerText(), 'No verdict')
    assert.equal(await page.evaluate(() => document.getAnimations().filter(a => a.playState === 'running').length), 0)
    checks.push('Runtime reduced motion stops playback and CSS motion while manual keyboard exploration remains available')

    for (const width of [320, 390, 768, 1440]) {
      await page.setViewportSize({ width, height: 1000 })
      for (const [name, locator] of [['map', map], ['comparison', compare], ['policy', policy], ['race', race]]) {
        await locator.scrollIntoViewIfNeeded()
        assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${name}: overflow at ${width}`)
        await locator.screenshot({ path: `qa/delta-journey/${name}-${width}.png` })
      }
    }
    checks.push('All four diagrams fit 320, 390, 768 and 1440px layouts')
    const chunk = fs.readdirSync('dist/assets').find(name => /^DeltaCase-.*\.js$/.test(name))
    assert(chunk)
    for (const id of ['delta-build-map', 'comparison', 'policy', 'verification']) {
      const cold = await browser.newPage({ viewport: { width: 390, height: 844 } })
      await cold.route(`${base}/assets/${chunk}`, async route => { const response = await route.fetch(); await new Promise(resolve => setTimeout(resolve, 750)); await route.fulfill({ response }) })
      await cold.goto(`${base}/projects/test-report-delta/#${id}`)
      await cold.getByTestId('delta-journey-map').waitFor()
      await cold.waitForFunction(id => { const top = document.getElementById(id)?.getBoundingClientRect().top; return top !== undefined && scrollY > 0 && top >= 0 && top < innerHeight / 2 }, id)
      await cold.close()
    }
    checks.push('Cold chapter links reach the requested section after delayed lazy loading')
    for (const path of ['/demos/test-report-delta/', '/evidence/test-report-delta-sample.json', '/evidence/test-report-delta-readme.md', '/evidence/test-report-delta-architecture.md', '/evidence/test-report-delta-development.md', '/evidence/test-report-delta-verification.json', '/downloads/test-report-delta.zip']) assert.equal((await page.request.get(base + path)).status(), 200, path)
    assert.deepEqual(errors, [])
    assert.deepEqual(external, [])
    assert.equal((await page.evaluate(() => indexedDB.databases())).length, 0)
    checks.push('Evidence and standalone demo are accessible; page has no errors, external requests or storage side effects')
    fs.writeFileSync('qa/delta-journey/results.json', JSON.stringify({ checkedAt: new Date().toISOString(), checks }, null, 2) + '\n')
    console.log(`${checks.length} delta journey checks passed`)
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
