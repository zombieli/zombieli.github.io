const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const base = process.env.BASE_URL || 'http://127.0.0.1:4174'

;(async () => {
  const browser = await chromium.launch({ headless: true, ...(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {}) })
  const page = await browser.newPage()
  const errors = []
  const checks = []
  page.on('pageerror', error => errors.push(error.message))
  page.setDefaultTimeout(6000)
  fs.mkdirSync('qa/journey', { recursive: true })
  try {
    await page.goto(base + '/projects/device-diagnostics/')
    await page.getByRole('navigation', { name: 'Build journey' }).waitFor()
    const links = page.locator('.journey-nav a')
    assert.equal(await links.count(), 6)
    for (const link of await links.all()) {
      const id = await link.getAttribute('href')
      await link.click()
      assert.equal(new URL(page.url()).hash, id)
      assert(await page.locator(id).isVisible())
    }
    checks.push('Six stages have usable native fragment links')
    const retry = page.locator('[data-testid="retry-decision"]')
    await retry.getByRole('button', { name: 'Disconnect and recover', exact: true }).click()
    assert.equal(await retry.locator('.decision-attempt').count(), 2)
    assert.match(await retry.innerText(), /connection_error/)
    assert.match(await retry.innerText(), /ok/)
    await retry.getByRole('button', { name: 'Malformed JSON', exact: true }).focus()
    await page.keyboard.press('Enter')
    assert.equal(await retry.locator('.decision-attempt').count(), 1)
    assert.match(await retry.innerText(), /protocol_error/)
    checks.push('Retry selector changes from two recorded recovery attempts to one non-retryable protocol error with keyboard')
    const expectation = page.locator('[data-testid="expectation-decision"]')
    await expectation.getByRole('button', { name: 'Expected fault', exact: true }).click()
    assert.equal(await expectation.locator('[data-field="outcome"]').innerText(), 'PASS')
    assert.equal(await expectation.locator('[data-field="expected"]').innerText(), 'validation_error')
    await expectation.getByRole('button', { name: 'Unexpected fault', exact: true }).focus()
    await page.keyboard.press('Enter')
    assert.equal(await expectation.locator('[data-field="outcome"]').innerText(), 'FAIL')
    assert.equal(await expectation.locator('[data-field="expected"]').innerText(), 'valid_status')
    assert.equal(await expectation.locator('[data-field="diagnostic"]').innerText(), 'validation_error')
    assert.match(await expectation.innerText(), /20261008T152057Z-fa5bb5f3/)
    checks.push('Expectation selector shows the saved PASS/FAIL, changed expectation, unchanged diagnostic and correct run identity')
    for (const width of [320, 390, 768, 1440]) {
      await page.setViewportSize({ width, height: 950 })
      assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Overflow at ${width}`)
      await page.evaluate(() => window.scrollTo(0, 0))
      await page.screenshot({ path: `qa/journey/page-${width}.png`, fullPage: true })
      await page.screenshot({ path: `qa/journey/top-${width}.png` })
      for (const target of [retry, expectation]) {
        await target.evaluate(element => element.scrollIntoView({ block: 'start' }))
        await page.screenshot({ path: `qa/journey/${await target.getAttribute('data-testid')}-${width}.png` })
      }
    }
    checks.push('320, 390, 768 and 1440px layouts have no document overflow')
    await page.route('**/evidence/failure-report.json', route => route.fulfill({ status: 503, body: 'Unavailable' }))
    await page.reload()
    await page.locator('#scenario').waitFor()
    await expectation.getByRole('button', { name: 'Unexpected fault', exact: true }).click()
    await expectation.getByRole('button', { name: 'Retry comparison evidence', exact: true }).waitFor()
    assert(await page.getByRole('link', { name: 'Download source, tests and reports', exact: true }).isVisible())
    await expectation.getByRole('button', { name: 'Expected fault', exact: true }).click()
    assert.equal(await expectation.locator('[data-field="outcome"]').innerText(), 'PASS')
    await page.unrouteAll()
    await expectation.getByRole('button', { name: 'Unexpected fault', exact: true }).click()
    await expectation.getByRole('button', { name: 'Retry comparison evidence', exact: true }).click()
    await page.waitForFunction(() => document.querySelector('[data-testid="expectation-decision"] [data-field="outcome"]')?.textContent === 'FAIL')
    checks.push('Missing failure report preserves normal result and downloads; retry restores comparison')
    const withoutRecovery = JSON.parse(fs.readFileSync('public/evidence/normal-report.json', 'utf8'))
    withoutRecovery.cases = withoutRecovery.cases.filter(item => item.scenario !== 'recover_after_disconnect')
    const withoutMissingField = JSON.parse(fs.readFileSync('public/evidence/failure-report.json', 'utf8'))
    withoutMissingField.cases = withoutMissingField.cases.filter(item => item.scenario !== 'missing_field')
    await page.route('**/evidence/normal-report.json', route => route.fulfill({ json: withoutRecovery }))
    await page.route('**/evidence/failure-report.json', route => route.fulfill({ json: withoutMissingField }))
    await page.reload()
    await page.locator('#scenario').waitFor()
    assert.equal(await retry.locator('.decision-attempt').count(), 0)
    assert.match(await retry.innerText(), /does not contain the selected scenario/)
    await retry.getByRole('button', { name: 'Malformed JSON', exact: true }).click()
    assert.equal(await retry.locator('.decision-attempt').count(), 1)
    await expectation.getByRole('button', { name: 'Unexpected fault', exact: true }).click()
    await page.waitForFunction(() => document.querySelector('[data-testid="expectation-decision"]')?.textContent.includes('does not contain the missing-field scenario'))
    assert.equal(await expectation.locator('[data-field="outcome"]').count(), 0)
    await expectation.getByRole('button', { name: 'Expected fault', exact: true }).click()
    assert.equal(await expectation.locator('[data-field="outcome"]').innerText(), 'PASS')
    checks.push('Missing case records show no fabricated attempts or outcomes; the remaining evidence stays usable')
    await page.unrouteAll()
    await page.reload()
    await page.locator('#scenario').waitFor()
    await page.setViewportSize({ width: 1440, height: 1200 })
    await page.locator('.journey-nav a[href="#reproduce"]').click()
    await page.waitForFunction(() => document.querySelector('.journey-nav [aria-current="step"]')?.getAttribute('href') === '#reproduce')
    checks.push('The final stage is marked current when reached through navigation')
    for (const path of ['/evidence/diagnostics-protocol.md', '/evidence/diagnostics-development.md', '/evidence/diagnostics-case-study.md', '/evidence/normal-run.txt', '/evidence/unexpected-failure-run.txt']) {
      assert.equal((await page.request.get(base + path)).status(), 200)
    }
    assert.deepEqual(errors, [])
    checks.push('Supporting documents resolve and no uncaught browser errors occurred')
    fs.writeFileSync('qa/journey/results.json', JSON.stringify({ checkedAt: new Date().toISOString(), checks }, null, 2))
    console.log(`${checks.length} journey checks passed`)
  } finally {
    await browser.close()
  }
})().catch(error => { console.error(error); process.exit(1) })
