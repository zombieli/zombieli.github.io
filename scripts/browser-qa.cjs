const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const fs = require('node:fs')
const assert = require('node:assert/strict')
const base = process.env.BASE_URL || 'http://127.0.0.1:4173'
;(async () => {
  fs.mkdirSync('qa',{recursive:true})
  const browser = await chromium.launch({headless:true, ...(process.env.CHROMIUM_PATH ? {executablePath:process.env.CHROMIUM_PATH} : {})})
  const context = await browser.newContext()
  const page = await context.newPage()
  const errors=[]; const checks=[]
  const catalogue=JSON.parse(fs.readFileSync('src/data/catalogue.json','utf8'))
  const activeCategories=catalogue.categories.filter(c=>catalogue.projects.some(p=>p.categoryId===c.id))
  page.on('pageerror', e => errors.push(e.message))
  for (const width of [360,390,768,1440]) {
    await page.setViewportSize({width,height:950})
    for (const path of ['/', '/projects/', ...catalogue.projects.map(p=>`/projects/${p.id}/`)]) {
      assert.equal((await page.goto(base+path)).status(),200)
      await page.locator('h1').waitFor()
      if(path === '/projects/device-diagnostics/') await page.locator('#scenario').waitFor()
      assert(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth),`Overflow ${path} ${width}`)
      const name = path==='/'?'home':path==='/projects/'?'collection':path.split('/')[2]
      await page.screenshot({path:`qa/${name}-${width}.png`,fullPage:true})
      if(width===390)await page.screenshot({path:`qa/${name}-mobile-viewport.png`})
      checks.push(`No horizontal overflow: ${path} ${width}px`)
    }
  }
  await page.goto(base)
  await page.keyboard.press('Tab')
  assert.equal(await page.locator(':focus').innerText(),'Skip to content')
  await page.keyboard.press('Enter')
  assert.equal(new URL(page.url()).hash,'#main')
  await page.getByRole('link',{name:'View case study: Device Diagnostics Lab',exact:true}).click()
  await page.locator('#scenario').selectOption('timeout')
  assert.match(await page.locator('.result-grid').innerText(),/PASS.*timeout.*2/s)
  assert.equal(await page.locator('.attempts li').count(),2)
  await page.locator('#scenario').selectOption('recover_after_disconnect')
  assert.match(await page.locator('.result-grid').innerText(),/PASS.*ok.*2/s)
  await page.locator('summary').first().click()
  assert.match(await page.locator('.attempts pre').first().innerText(),/get_status/)
  checks.push('Keyboard skip link; home to case; timeout and recovery evidence; raw request disclosure')
  await page.goto(base)
  assert.equal(await page.locator('.featured-grid .catalogue-card').count(),activeCategories.length)
  for (const category of activeCategories) assert.equal(await page.locator(`.featured-grid [data-category="${category.id}"]`).count(),1)
  checks.push('Homepage has exactly one representative per published category')
  await page.getByRole('link',{name:'Browse all projects'}).click()
  await page.getByRole('heading',{name:'Explore the work.'}).waitFor()
  assert.equal(await page.locator('.library-grid .catalogue-card').count(),catalogue.projects.length)
  assert.equal(await page.locator('.category-filters button').count(),catalogue.categories.length+1)
  assert.equal(await page.locator('.future-grid article').count(),catalogue.categories.length-activeCategories.length)
  checks.push('Collection shows all published work, category counts and honest future directions')
  assert.equal(await page.locator('.roadmap-grid article').count(),activeCategories.filter(c=>c.ideas.length).length)
  for (const category of activeCategories.filter(c=>c.ideas.length)) {
    assert.match(await page.locator(`.roadmap-grid [data-category="${category.id}"]`).innerText(),/POSSIBLE NEXT STEPS/)
  }
  checks.push('Populated categories keep a separately labelled future roadmap')
  const webButton=page.getByRole('button',{name:/^Web applications/})
  await webButton.click()
  assert.equal(new URL(page.url()).searchParams.get('category'),'web-applications')
  assert.equal(await webButton.getAttribute('aria-pressed'),'true')
  assert.equal(await page.locator('.library-grid .catalogue-card').count(),catalogue.projects.filter(p=>p.categoryId==='web-applications').length)
  await page.reload()
  assert.equal(await webButton.getAttribute('aria-pressed'),'true')
  checks.push('Category URL survives reload and exposes selected state')
  await page.getByRole('button',{name:/^Data & simulation/}).focus()
  await page.keyboard.press('Enter')
  assert.equal(new URL(page.url()).searchParams.get('category'),'data-simulation')
  await page.goBack()
  assert.equal(await webButton.getAttribute('aria-pressed'),'true')
  await page.goForward()
  assert.equal(await page.getByRole('button',{name:/^Data & simulation/}).getAttribute('aria-pressed'),'true')
  checks.push('Keyboard category selection and browser back/forward restore filters')
  await page.getByRole('button',{name:/^All projects/}).click()
  await page.getByLabel('Search projects',{exact:true}).fill(' ＰＹＴＨＯＮ   diagnostics ')
  assert.equal(await page.locator('.library-grid .catalogue-card').count(),1)
  assert.equal(await page.locator('.library-grid .catalogue-card').getAttribute('data-project'),'device-diagnostics')
  await page.reload()
  assert.equal(await page.locator('.library-grid .catalogue-card').count(),1)
  await page.getByLabel('Search projects',{exact:true}).fill('no-such-project-9481')
  assert(await page.getByRole('heading',{name:'No projects match these filters.'}).isVisible())
  assert.equal(await page.locator('.result-count').innerText(),'0 projects')
  await page.getByRole('button',{name:'Show all projects',exact:true}).click()
  assert.equal(await page.getByLabel('Search projects',{exact:true}).inputValue(),'')
  assert.equal(await page.locator('.library-grid .catalogue-card').count(),catalogue.projects.length)
  checks.push('Technology search, URL persistence, zero results and reset work together')
  await page.getByLabel('Sort by',{exact:true}).selectOption('title')
  assert.equal(new URL(page.url()).searchParams.get('sort'),'title')
  const titles=await page.locator('.library-grid h3').allTextContents()
  assert.deepEqual(titles,[...titles].sort((a,b)=>a.localeCompare(b,'en')))
  await page.reload()
  assert.equal(await page.getByLabel('Sort by',{exact:true}).inputValue(),'title')
  checks.push('Title sorting is deterministic and shareable')
  const future=catalogue.categories.find(c=>!activeCategories.some(active=>active.id===c.id))
  if(future){
    await page.getByRole('button',{name:new RegExp('^'+future.label.replace(/[.*+?^${}()|[\]\\]/g,'\\$&'))}).click()
    assert(await page.getByRole('heading',{name:'No published projects here yet.'}).isVisible())
    assert.equal(await page.locator('.library-grid .catalogue-card').count(),0)
    assert.match(await page.locator('.catalogue-empty').innerText(),/not completed projects/)
    checks.push('Empty future category contains labelled ideas and no invented project cards')
  }
  await page.goto(base+'/projects/?category=removed&q=python&sort=invalid')
  assert(await page.getByRole('status').filter({hasText:'This category is unavailable'}).isVisible())
  assert.equal(await page.getByRole('button',{name:/^All projects/}).getAttribute('aria-pressed'),'true')
  assert.equal(await page.getByLabel('Sort by',{exact:true}).inputValue(),'updated')
  checks.push('Outdated category URLs fall back to all categories without dropping the search')
  await page.goto(base)
  await page.locator('.featured-grid').getByRole('link',{name:'Devices & testing',exact:true}).click()
  assert.equal(await page.getByRole('button',{name:/^Devices & testing/}).getAttribute('aria-pressed'),'true')
  await page.getByRole('link',{name:'View case study: Device Diagnostics Lab',exact:true}).click()
  await page.getByRole('link',{name:'All projects',exact:true}).click()
  assert.equal(new URL(page.url()).pathname,'/projects/')
  checks.push('Homepage category links, collection case links and return navigation work')
  for (const path of ['/resume/leon-li-resume.pdf','/evidence/normal-report.json','/evidence/normal-cases.csv','/evidence/failure-report.json','/downloads/device-diagnostics-lab.zip','/downloads/field-service-workflow.zip','/downloads/scheduling-simulation-study.zip','/evidence/scheduling-results.json','/media/device-evidence-walkthrough.webm','/media/device-evidence.vtt']) {
    const r=await context.request.get(base+path); assert.equal(r.status(),200)
    if(path.endsWith('.pdf')) assert((await r.body()).subarray(0,5).equals(Buffer.from('%PDF-')))
    if(path.endsWith('.vtt')) assert.match(r.headers()['content-type'],/^text\/vtt/)
    checks.push(`Resource loads: ${path}`)
  }
  await page.setViewportSize({width:390,height:844})
  await page.goto(base)
  const menu=page.getByRole('button',{name:'Menu',exact:true})
  await menu.click(); assert.equal(await menu.getAttribute('aria-expanded'),'true')
  await page.getByRole('navigation').getByRole('link',{name:'About',exact:true}).click()
  assert.equal(await menu.getAttribute('aria-expanded'),'false')
  checks.push('Mobile navigation opens, navigates and closes')
  await page.route('**/evidence/normal-report.json',route=>route.abort())
  await page.goto(base+'/projects/device-diagnostics/')
  await page.getByRole('alert').waitFor()
  assert(await page.getByRole('heading',{name:'Show success. Preserve failure.'}).isVisible())
  checks.push('Evidence fetch failure retains readable case and download links')
  await page.unrouteAll()
  await page.goto(base+'/projects/device-diagnostics/')
  await page.locator('video').evaluate(video=>{video.preload='metadata';video.load()})
  await page.waitForFunction(()=>document.querySelector('video').readyState>=1)
  assert((await page.locator('video').evaluate(video=>video.duration))>=60)
  checks.push('Video metadata loads and recorded duration is at least 60 seconds')
  await page.goto(base+'/projects/field-service/')
  await page.getByRole('link',{name:'Open interactive demo'}).click()
  await page.getByRole('heading',{name:'Work orders',exact:true}).waitFor()
  assert.match(await page.locator('.demo-banner').innerText(),/DEMO DATA/)
  assert.equal(await page.locator('.order').count(),2)
  checks.push('Portfolio opens bundled synthetic workflow demo at correct base path')
  await page.goto(base+'/projects/scheduling/')
  assert.match(await page.locator('tbody').innerText(),/26.16.*27.*2.91.*93/s)
  checks.push('Scheduling counterexample table matches recorded experiment')
  assert.equal((await page.goto(base+'/does-not-exist')).status(),404)
  assert.match(await page.locator('body').innerText(),/not found/i)
  checks.push('Unknown route returns real 404')
  assert.deepEqual(errors,[])
  checks.push('No uncaught browser errors')
  const assets=fs.readdirSync('dist/assets').map(name=>({name,bytes:fs.statSync('dist/assets/'+name).size}))
  fs.writeFileSync('qa/results.json',JSON.stringify({executed_at_utc:new Date().toISOString(),browser:await browser.version(),checks,assets,limitations:'Chromium functional checks; not a WCAG audit, Lighthouse score or public deployment verification.'},null,2))
  console.log(`${checks.length} browser checks passed`)
  await browser.close()
})().catch(error=>{console.error(error);process.exit(1)})
