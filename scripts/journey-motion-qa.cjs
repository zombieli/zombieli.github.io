const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const base = process.env.BASE_URL || 'http://127.0.0.1:4174'

;(async () => {
  const browser = await chromium.launch({ headless: true, ...(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {}) })
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  const errors = []
  const checks = []
  page.on('pageerror', error => errors.push(error.message))
  page.setDefaultTimeout(6000)
  fs.mkdirSync('qa/journey-motion', { recursive: true })
  try {
    await page.goto(base + '/projects/device-diagnostics/')
    const map = page.locator('[data-testid="journey-map"]')
    await map.waitFor()
    assert.equal(await map.locator('button[data-stage]').count(), 6)
    await map.locator('[data-stage="contract"]').click()
    assert.equal(await map.locator('[data-stage="contract"]').getAttribute('aria-pressed'), 'true')
    assert.match(await map.locator('[data-testid="journey-map-artifact"]').innerText(), /diagnostics-sim\/1/)
    await map.locator('[data-stage="reproduce"]').focus()
    await page.keyboard.press('Enter')
    assert.match(await map.locator('[data-testid="journey-map-artifact"]').innerText(), /report\.json/)
    assert.equal(await map.getByRole('link', { name: 'Explore this stage', exact: true }).getAttribute('href'), '#reproduce')
    checks.push('Six-node build map changes its artifact and chapter link by mouse and keyboard')
    const architecture = page.locator('[data-testid="architecture-map"]')
    await architecture.getByRole('button', { name: 'Inspect simulator', exact: true }).click()
    assert.match(await architecture.locator('.architecture-detail').innerText(), /simulator\.py/)
    await architecture.getByRole('button', { name: 'Inspect reporting', exact: true }).focus()
    await page.keyboard.press('Enter')
    assert.match(await architecture.locator('.architecture-detail').innerText(), /reporting\.py/)
    checks.push('Architecture nodes reveal the corresponding source responsibility')
    const retry = page.locator('[data-testid="retry-decision"]')
    const retryFlow = page.locator('[data-testid="retry-flow"]')
    await retry.getByRole('button', { name: 'Disconnect and recover', exact: true }).click()
    assert.equal(await retryFlow.getAttribute('data-playing'), 'false')
    await retryFlow.getByRole('button', { name: 'Replay flow', exact: true }).click()
    await page.waitForFunction(() => document.querySelector('[data-testid="retry-flow"]')?.getAttribute('data-playing') === 'true')
    await retryFlow.getByRole('button', { name: 'Pause flow', exact: true }).click()
    assert.equal(await retryFlow.getAttribute('data-playing'), 'false')
    await retryFlow.locator('button[data-flow-step]').last().click()
    assert.equal(await retryFlow.locator('button[data-flow-step]').last().getAttribute('aria-current'), 'step')
    await retryFlow.getByRole('button', { name: 'Replay flow', exact: true }).click()
    await retry.getByRole('button', { name: 'Malformed JSON', exact: true }).click()
    await page.waitForFunction(() => document.querySelector('[data-testid="retry-flow"]')?.getAttribute('data-playing') === 'false', null, { timeout: 12000 })
    assert.match(await retryFlow.innerText(), /protocol_error/)
    assert.doesNotMatch(await retryFlow.innerText(), /connection_error/)
    checks.push('Recorded retry flow starts, pauses, steps and cancels the old sequence when switching scenario')
    const expectation = page.locator('[data-testid="expectation-decision"]')
    const expectedFlow = page.locator('[data-testid="expectation-flow"]')
    await expectation.getByRole('button', { name: 'Unexpected fault', exact: true }).click()
    assert.equal(await expectedFlow.getAttribute('data-playing'), 'false')
    await expectedFlow.getByRole('button', { name: 'Replay flow', exact: true }).click()
    await page.waitForFunction(() => document.querySelector('[data-testid="expectation-flow"]')?.getAttribute('data-playing') === 'true')
    await expectedFlow.getByRole('button', { name: 'Pause flow', exact: true }).click()
    await expectedFlow.locator('button[data-flow-step]').last().click()
    assert.match(await expectedFlow.innerText(), /FAIL/)
    assert.equal(await expectation.locator('[data-field="outcome"]').innerText(), 'FAIL')
    checks.push('Expectation diagram and saved result agree on FAIL; step selection is available')
    await retryFlow.getByRole('button', { name: 'Replay flow', exact: true }).click()
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.waitForFunction(() => document.querySelector('[data-testid="retry-flow"]')?.getAttribute('data-playing') === 'false')
    await retry.getByRole('button', { name: 'Disconnect and recover', exact: true }).click()
    assert.equal(await retryFlow.getAttribute('data-playing'), 'false')
    await expectation.getByRole('button', { name: 'Expected fault', exact: true }).click()
    assert.equal(await expectedFlow.getAttribute('data-playing'), 'false')
    assert.equal(await expectation.locator('[data-field="outcome"]').innerText(), 'PASS')
    await map.locator('[data-stage="contract"]').click()
    await architecture.getByRole('button', { name: 'Inspect runner', exact: true }).click()
    const running = await page.evaluate(() => document.getAnimations().filter(item => item.playState === 'running').length)
    assert.equal(running, 0)
    checks.push('Reduced-motion stops active playback and preserves clickable diagrams and complete results')
    for (const width of [320, 390, 768, 1440]) {
      await page.setViewportSize({ width, height: 1000 })
      assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Overflow at ${width}`)
      for (const [name, target] of [['map', map], ['architecture', architecture], ['retry', retryFlow], ['expectation', expectedFlow]]) {
        await target.evaluate(element => element.scrollIntoView({ block: 'start' }))
        await page.screenshot({ path: `qa/journey-motion/${name}-${width}.png` })
        assert(await target.evaluate(element => element.scrollWidth <= element.clientWidth + 1), `Diagram overflow: ${name} ${width}`)
      }
    }
    checks.push('All four diagrams fit 320, 390, 768 and 1440px screens')
    assert.deepEqual(errors, [])
    fs.writeFileSync('qa/journey-motion/results.json', JSON.stringify({ checkedAt: new Date().toISOString(), checks }, null, 2))
    console.log(`${checks.length} animated-diagram checks passed`)
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exit(1) })
