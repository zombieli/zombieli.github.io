const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const fs=require('node:fs')
;(async()=>{
  fs.mkdirSync('public/media',{recursive:true})
  const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH,headless:true})
  const context=await browser.newContext({viewport:{width:1280,height:900},recordVideo:{dir:'qa/video',size:{width:1280,height:900}}})
  const page=await context.newPage()
  await page.goto('http://127.0.0.1:4173/projects/device-diagnostics/')
  await page.waitForTimeout(7000)
  await page.locator('#demo').scrollIntoViewIfNeeded()
  await page.locator('#scenario').waitFor()
  await page.waitForTimeout(8000)
  await page.locator('#scenario').selectOption('timeout')
  await page.waitForTimeout(9000)
  await page.locator('summary').first().click()
  await page.waitForTimeout(8000)
  await page.locator('summary').first().click()
  await page.locator('#scenario').selectOption('recover_after_disconnect')
  await page.waitForTimeout(10000)
  await page.locator('summary').last().click()
  await page.locator('.attempts li').last().scrollIntoViewIfNeeded()
  await page.waitForTimeout(10000)
  await page.locator('#results').scrollIntoViewIfNeeded()
  await page.waitForTimeout(10000)
  const video=page.video()
  await context.close()
  await video.saveAs('public/media/device-evidence-walkthrough.webm')
  await browser.close()
  console.log('Recorded saved-evidence viewer walkthrough; this is not live hardware footage.')
})().catch(e=>{console.error(e);process.exit(1)})
