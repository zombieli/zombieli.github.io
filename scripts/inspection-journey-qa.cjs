const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const base = process.env.BASE_URL || 'http://127.0.0.1:4174'
;(async () => {
  const browser = await chromium.launch({ headless: true, ...(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {}) })
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  const errors = [], checks = []
  page.on('pageerror', error => errors.push(error.message))
  page.setDefaultTimeout(6000)
  fs.mkdirSync('qa/inspection-journey', { recursive: true })
  try {
    await page.goto(base + '/projects/inspection-notebook/')
    const map = page.getByTestId('inspection-journey-map')
    await map.waitFor()
    assert.equal(await map.locator('button[data-stage]').count(), 6)
    for (const id of ['scope', 'records', 'offline', 'recovery', 'verification', 'reproduce']) {
      assert.equal(await page.locator(`nav[aria-label="Build journey"] a[href="#${id}"]`).count(), 1)
      await map.locator(`[data-stage="${id}"]`).click()
      assert.equal(await map.getByRole('link', { name: 'Explore this stage' }).getAttribute('href'), '#' + id)
    }
    await map.locator('[data-stage="recovery"]').focus()
    await page.keyboard.press('Enter')
    assert.match(await map.getByTestId('inspection-map-artifact').innerText(), /transaction|import|restore/i)
    checks.push('Six source-backed stages have clickable artifacts and keyboard chapter links')

    const record = page.getByTestId('inspection-record-demo')
    const notes = record.getByLabel('Notes (optional)')
    const message = record.getByTestId('inspection-record-message')
    const saved = record.getByTestId('inspection-record-saved')
    await record.getByRole('button', { name: 'Submit record', exact: true }).click()
    assert.match(await message.innerText(), /Select a fictional asset/)
    assert.equal(await record.getAttribute('data-pending'), 'false')
    await notes.fill('Keep this field note.')
    await record.getByRole('button', { name: 'Save draft', exact: true }).click()
    assert.equal(await record.getAttribute('data-pending'), 'true')
    for (const input of await record.locator('fieldset input, fieldset select, fieldset textarea').all()) assert(await input.isDisabled())
    assert(await record.getByRole('button', { name: 'Close editor', exact: true }).isDisabled())
    assert(!((await saved.innerText()).includes('Keep this field note.')))
    await record.getByRole('button', { name: 'Fail write', exact: true }).click()
    assert.equal(await notes.inputValue(), 'Keep this field note.')
    assert(await notes.isEnabled())
    await record.getByRole('button', { name: 'Save draft', exact: true }).click()
    await record.getByRole('button', { name: 'Complete write', exact: true }).click()
    assert.match(await saved.innerText(), /Keep this field note/)
    assert.equal(await record.locator('[data-record-saved-timestamp]').innerText(), '02:00:00.001Z')
    checks.push('Pending writes lock fields and Close; failures preserve input and only completion changes saved data')

    await record.getByLabel('Fictional asset', { exact: true }).selectOption('TRN-101')
    await record.getByLabel('Condition', { exact: true }).selectOption('watch')
    await record.getByRole('button', { name: 'Submit record', exact: true }).click()
    assert.match(await message.innerText(), /Complete every checklist item/)
    for (const checkbox of await record.locator('input[type="checkbox"]').all()) await checkbox.check()
    await record.getByRole('button', { name: 'Submit record', exact: true }).click()
    assert.equal(await record.locator('[data-record-saved-status]').innerText(), 'draft')
    await record.getByRole('button', { name: 'Complete write', exact: true }).click()
    assert.equal(await record.locator('[data-record-saved-status]').innerText(), 'submitted')
    assert.equal(await record.locator('[data-record-saved-timestamp]').innerText(), '02:00:00.002Z')
    assert(await notes.isDisabled())
    assert(await record.getByRole('button', { name: 'Submit record', exact: true }).isDisabled())
    await record.getByRole('button', { name: 'Close editor', exact: true }).click()
    await record.getByRole('button', { name: 'Reopen editor', exact: true }).click()
    assert(await notes.isDisabled())
    checks.push('Submission enforces all checks, advances time and keeps saved records read-only')

    await record.getByRole('button', { name: 'Reset example', exact: true }).click()
    await notes.fill('Unsaved local note.')
    await record.getByRole('button', { name: 'Simulate another tab', exact: true }).click()
    await record.getByRole('button', { name: 'Save draft', exact: true }).click()
    assert.match(await message.innerText(), /changed in another tab/)
    assert.equal(await notes.inputValue(), 'Unsaved local note.')
    assert.match(await saved.innerText(), /Saved from another tab/)
    assert.equal(await record.getAttribute('data-pending'), 'false')
    await record.getByRole('button', { name: 'Reset example', exact: true }).click()
    checks.push('A stale example tab cannot overwrite the newer saved draft')

    const offline = page.getByTestId('inspection-offline')
    for (const [id, expected] of [['first', /No cached shell/], ['ready', /Ready to continue/], ['unavailable', /Record actions stay unavailable/]]) {
      await offline.locator(`[data-offline-mode="${id}"]`).click()
      assert.match(await offline.getByTestId('inspection-offline-result').innerText(), expected)
      await offline.locator('[data-offline-node="2"]').click()
      assert.equal(await offline.getAttribute('data-playing'), 'false')
    }
    checks.push('Offline map distinguishes missing cache, prepared access and unavailable record storage')

    const backup = page.getByTestId('inspection-import-demo')
    const outcome = () => backup.getByTestId('inspection-import-result').getAttribute('data-outcome')
    const count = () => backup.getByTestId('inspection-import-committed').getAttribute('data-count')
    await backup.getByRole('button', { name: 'Inspect Queue adds', exact: true }).click()
    assert.equal(await count(), '1')
    assert.match(await backup.getByTestId('inspection-import-pending').innerText(), /new-before/)
    await backup.getByRole('button', { name: 'Inspect Commit or abort', exact: true }).click()
    assert.equal(await count(), '3')
    assert.equal(await outcome(), 'committed')
    await backup.getByRole('button', { name: 'Conflicting ID', exact: true }).click()
    await backup.getByRole('button', { name: 'Inspect Queue adds', exact: true }).click()
    await backup.getByRole('button', { name: 'Next step', exact: true }).click()
    assert.equal(await count(), '1')
    assert.match(await backup.getByTestId('inspection-import-pending').innerText(), /new-before/)
    await backup.getByRole('button', { name: 'Next step', exact: true }).click()
    assert.equal(await outcome(), 'aborted')
    assert.equal(await count(), '1')
    assert.match(await backup.getByTestId('inspection-import-pending').innerText(), /None/)
    for (const [name, expectedCount, expectedOutcome] of [['Invalid backup', '1', 'rejected'], ['Notebook full', '1000', 'aborted']]) {
      await backup.getByRole('button', { name, exact: true }).click()
      while (await backup.getByRole('button', { name: 'Next step', exact: true }).isEnabled()) await backup.getByRole('button', { name: 'Next step', exact: true }).click()
      assert.equal(await count(), expectedCount)
      assert.equal(await outcome(), expectedOutcome)
    }
    checks.push('Clean import commits atomically; conflicting IDs, invalid types and capacity preserve saved records')
    await backup.getByRole('button', { name: 'Clean import', exact: true }).click()
    await backup.getByRole('button', { name: 'Replay import', exact: true }).click()
    assert.equal(await backup.getAttribute('data-playing'), 'true')
    await backup.getByRole('button', { name: 'Pause import', exact: true }).click()
    const paused = await backup.getByTestId('inspection-import-step').innerText()
    await page.waitForTimeout(1100)
    assert.equal(await backup.getByTestId('inspection-import-step').innerText(), paused)
    await backup.getByRole('button', { name: 'Replay import', exact: true }).click()
    await backup.getByRole('button', { name: 'Invalid backup', exact: true }).click()
    await page.waitForTimeout(1100)
    assert.equal(await backup.getAttribute('data-playing'), 'false')
    assert.equal(await backup.getByTestId('inspection-import-step').innerText(), '1 / 2')
    checks.push('Backup replay pauses and scenario changes cancel the previous transaction animation')

    await backup.getByRole('button', { name: 'Clean import', exact: true }).click()
    await backup.getByRole('button', { name: 'Replay import', exact: true }).click()
    await offline.getByRole('button', { name: 'Replay offline path', exact: true }).click()
    await record.getByRole('button', { name: 'Save draft', exact: true }).click()
    await map.locator('[data-stage="offline"]').click()
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.waitForFunction(() => ['inspection-import-demo', 'inspection-offline', 'inspection-record-demo'].every(id => document.querySelector(`[data-testid="${id}"]`).dataset.playing === 'false'))
    await record.getByRole('button', { name: 'Complete write', exact: true }).click()
    await backup.getByRole('button', { name: 'Inspect Commit or abort', exact: true }).focus()
    await page.keyboard.press('Enter')
    assert.equal(await count(), '3')
    assert.equal(await page.evaluate(() => document.getAnimations().filter(a => a.playState === 'running').length), 0)
    checks.push('Live reduced-motion changes stop animation while keyboard/manual controls remain available')
    assert.equal((await page.evaluate(() => indexedDB.databases())).length, 0)
    assert.equal((await page.evaluate(() => navigator.serviceWorker.getRegistrations().then(items => items.length))), 0)
    checks.push('Case-page interactions create no IndexedDB database or service worker')

    for (const width of [320, 390, 768, 1440]) {
      await page.setViewportSize({ width, height: 1000 })
      for (const [name, locator] of [['map', map], ['record', record], ['offline', offline], ['import', backup]]) {
        await locator.scrollIntoViewIfNeeded()
        assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${name}: overflow at ${width}`)
        await locator.screenshot({ path: `qa/inspection-journey/${name}-${width}.png` })
      }
    }
    checks.push('All diagrams fit 320, 390, 768 and 1440px screens')
    const chunk = fs.readdirSync('dist/assets').find(name => /^InspectionCase-.*\.js$/.test(name))
    assert(chunk)
    for (const id of ['inspection-build-map', 'records', 'recovery']) {
      const cold = await browser.newPage({ viewport: { width: 390, height: 844 } })
      await cold.route(`${base}/assets/${chunk}`, async route => {
        const response = await route.fetch()
        await new Promise(resolve => setTimeout(resolve, 750))
        await route.fulfill({ response })
      })
      await cold.goto(`${base}/projects/inspection-notebook/#${id}`)
      await cold.getByTestId('inspection-journey-map').waitFor()
      await cold.waitForFunction(id => {
        const top = document.getElementById(id)?.getBoundingClientRect().top
        return top !== undefined && scrollY > 0 && top >= 0 && top < innerHeight / 2
      }, id)
      await cold.close()
    }
    checks.push('Cold chapter links reach their target after delayed case loading')
    for (const path of ['/demos/inspection-notebook/', '/evidence/inspection-notebook-readme.md', '/evidence/inspection-notebook-architecture.md', '/evidence/inspection-notebook-development.md', '/evidence/inspection-notebook-verification.json', '/downloads/inspection-notebook.zip']) assert.equal((await page.request.get(base + path)).status(), 200, path)
    assert.deepEqual(errors, [])
    checks.push('Standalone demo, source and dated evidence remain available without page errors')
    fs.writeFileSync('qa/inspection-journey/results.json', JSON.stringify({ checkedAt: new Date().toISOString(), checks }, null, 2) + '\n')
    console.log(`${checks.length} inspection journey checks passed`)
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
